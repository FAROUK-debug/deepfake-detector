"""
app.py — Gradio web interface: upload a face, get REAL / FAKE, confidence and a Grad-CAM heatmap.
Run: python app.py      (opens http://127.0.0.1:7860)
"""

import os
import time
from pathlib import Path

import gradio as gr
from PIL import Image

import detector

# Refuse decompression bombs: a face photo never needs more than ~25 megapixels.
Image.MAX_IMAGE_PIXELS = 25_000_000
MIN_SIDE = 64
EXAMPLES = sorted(str(p) for p in (Path(__file__).parent / "examples").glob("*.jpg"))

DISCLAIMER = (
    "⚠️ **Research demo, not proof.** Trained on StyleGAN faces (Kaggle *140k Real and Fake Faces*). "
    "It can be wrong, and it was not trained on images from newer generators (diffusion models, face swaps). "
    "Images are processed in memory and not stored."
)


def analyse(img: Image.Image):
    if img is None:
        raise gr.Error("Upload a face image first.")
    if min(img.size) < MIN_SIDE:
        raise gr.Error(f"Image too small ({img.size[0]}×{img.size[1]}). Use at least {MIN_SIDE}×{MIN_SIDE} pixels.")

    started = time.perf_counter()
    pred = detector.predict(img)
    heat = detector.gradcam(img, pred.label)
    ms = (time.perf_counter() - started) * 1000

    other = "FAKE" if pred.label == "REAL" else "REAL"
    details = (
        f"**{pred.label}** with {pred.confidence:.0%} confidence  \n"
        f"Model output P(real) = `{pred.p_real:.3f}`, decision threshold = `{detector.THRESHOLD}` "
        f"(below → FAKE)  \n"
        f"The heatmap shows the regions that pushed the model towards **{pred.label}** "
        f"(red = strongest). Time: {ms:.0f} ms"
    )
    return {pred.label: pred.confidence, other: 1 - pred.confidence}, detector.overlay(img, heat), details


with gr.Blocks(title="Deepfake Face Detector", theme=gr.themes.Soft()) as demo:
    gr.Markdown("# 🕵️ Deepfake Face Detector\nIs this face a real photo or generated by AI? "
                "VGG16 fine-tuned on 20,000 faces, with Grad-CAM to show *why*.")
    gr.Markdown(DISCLAIMER)
    with gr.Row():
        with gr.Column():
            image_in = gr.Image(type="pil", label="Face image", sources=["upload", "clipboard"], height=320)
            run = gr.Button("Analyse", variant="primary")
        with gr.Column():
            label_out = gr.Label(label="Prediction", num_top_classes=2)
            heat_out = gr.Image(label="Grad-CAM: where the model looked", height=320)
            details_out = gr.Markdown()
    gr.Examples(EXAMPLES, inputs=image_in, outputs=[label_out, heat_out, details_out], fn=analyse,
                run_on_click=True, cache_examples=False,
                label="Examples from the test set (not used in training): click one")
    run.click(analyse, inputs=image_in, outputs=[label_out, heat_out, details_out])
    image_in.upload(analyse, inputs=image_in, outputs=[label_out, heat_out, details_out])


if __name__ == "__main__":
    detector.load_model()  # load (and download if needed) before the first request
    demo.queue(max_size=20).launch(
        server_name=os.getenv("HOST", "127.0.0.1"),
        server_port=int(os.getenv("PORT", "7860")),
        max_file_size="5mb",
    )
